def as_joint_limits(v):
    """把任意形式的关节限位归一化为 (6, 2) 的 float 数组。"""
    return np.asarray(v, dtype=float).reshape(6, 2)


def as_workspace(ws):
    """把 dict 形式的工作空间归一化，并校验每轴 [low, high] 顺序。"""
    out = {}
    for axis in ("x", "y", "z"):
        lo, hi = float(ws[axis][0]), float(ws[axis][1])
        if hi <= lo:
            raise ValueError(f"workspace {axis} 区间非法: [{lo}, {hi}]")
        out[axis] = [lo, hi]
    return out
